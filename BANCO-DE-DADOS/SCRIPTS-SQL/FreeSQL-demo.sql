CREATE TABLE EMPREGADO (
    NOME      VARCHAR2(15) NOT NULL,
    SOBRENOME VARCHAR2(15) NOT NULL,
    CPF       CHAR(11) PRIMARY KEY,
    DATANASC  DATE NOT NULL,
    ENDERECO  VARCHAR2(30),
    SALARIO   NUMBER(10, 2),
    DEPTO     NUMBER(3) NOT NULL,
    EMAIL     VARCHAR2(25) UNIQUE,
    FOREIGN KEY ( DEPTO )
        REFERENCES DEPARTAMENTO ( NUMERODEP )
);

CREATE TABLE DEPARTAMENTO (
    NOMEDEP    VARCHAR2(15) NOT NULL UNIQUE,
    NUMERODEP  NUMBER(3) PRIMARY KEY,
    CPFGERENTE CHAR(11) NOT NULL,
    FOREIGN KEY ( CPFGERENTE )
        REFERENCES EMPREGADO ( CPF )
);

